// One-time testnet setup. Run AFTER deploying the contracts.
// Creates throwaway wallets for the bots (price bot, keeper, and a pair of seeders per market), sends each a tiny amount of
// test ETH from the deployer, mints test $WIF to the seeders, and writes everything to .env.testnet (git-ignored).
// Only addresses are printed. Private keys are written to the file and never to the terminal.
//
// Usage: DEPLOYER_PRIVATE_KEY=0x... TAPE=0x... WIF=0x... FEED_NVDA=0x... FEED_TSLA=0x... FEED_AAPL=0x... \
//        node scripts/testnet-setup.mjs
import { createPublicClient, createWalletClient, defineChain, http, parseAbi, parseEther, parseUnits } from "viem";
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";
import { writeFileSync } from "node:fs";

const need = (k) => {
  const v = process.env[k];
  if (!v) {
    console.error(`Missing env var ${k}.`);
    process.exit(1);
  }
  return v;
};

const RPC = process.env.NEXT_PUBLIC_RPC_URL || "https://rpc.testnet.chain.robinhood.com";
const CHAIN_ID = Number(process.env.NEXT_PUBLIC_CHAIN_ID || 46630);
const ETH_EACH = process.env.ETH_EACH || "0.0005"; // gas is ~0.01 gwei on the testnet, so this lasts a very long time
const MARKETS = 3;

const chain = defineChain({
  id: CHAIN_ID,
  name: "Robinhood Chain Testnet",
  nativeCurrency: { name: "Ether", symbol: "ETH", decimals: 18 },
  rpcUrls: { default: { http: [RPC] } },
});
const deployer = privateKeyToAccount(need("DEPLOYER_PRIVATE_KEY"));
const pub = createPublicClient({ chain, transport: http() });
const wallet = createWalletClient({ account: deployer, chain, transport: http() });
const wifAbi = parseAbi(["function mint(address to, uint256 amount)"]);

// The feeds only accept writes from the `pusher` address chosen at deploy time (the deployer by default).
// So the price bot must use that same key: pass PUSHER_PRIVATE_KEY to reuse it instead of generating a new one.
const keys = {
  PUSHER_PRIVATE_KEY: process.env.PUSHER_PRIVATE_KEY || generatePrivateKey(),
  KEEPER_PRIVATE_KEY: generatePrivateKey(),
};
for (let i = 0; i < MARKETS; i++) {
  keys[`SEEDER_${i}_UP_PRIVATE_KEY`] = generatePrivateKey();
  keys[`SEEDER_${i}_DOWN_PRIVATE_KEY`] = generatePrivateKey();
}

console.log(`deployer ${deployer.address}`);
const bal = await pub.getBalance({ address: deployer.address });
console.log(`deployer balance ${Number(bal) / 1e18} ETH`);

for (const [name, key] of Object.entries(keys)) {
  const to = privateKeyToAccount(key).address;
  if (to.toLowerCase() !== deployer.address.toLowerCase()) {
    const h1 = await wallet.sendTransaction({ to, value: parseEther(ETH_EACH) });
    await pub.waitForTransactionReceipt({ hash: h1 });
  }
  if (name.startsWith("SEEDER_")) {
    const h2 = await wallet.writeContract({ address: need("WIF"), abi: wifAbi, functionName: "mint", args: [to, parseUnits("100000", 18)] });
    await pub.waitForTransactionReceipt({ hash: h2 });
  }
  console.log(`funded ${name.replace("_PRIVATE_KEY", "").padEnd(18)} ${to}`);
}

const env = [
  "# Generated by scripts/testnet-setup.mjs. Throwaway testnet keys. Never commit this file.",
  `NEXT_PUBLIC_CHAIN_ID=${CHAIN_ID}`,
  "NEXT_PUBLIC_CHAIN_NAME=Robinhood Chain Testnet",
  `NEXT_PUBLIC_RPC_URL=${RPC}`,
  "NEXT_PUBLIC_EXPLORER_URL=https://explorer.testnet.chain.robinhood.com",
  `NEXT_PUBLIC_TAPE_ADDRESS=${need("TAPE")}`,
  `NEXT_PUBLIC_WIF_ADDRESS=${need("WIF")}`,
  "NEXT_PUBLIC_WIF_DECIMALS=18",
  "NEXT_PUBLIC_TEST_FAUCET=true",
  `FEED_NVDA=${need("FEED_NVDA")}`,
  `FEED_TSLA=${need("FEED_TSLA")}`,
  `FEED_AAPL=${need("FEED_AAPL")}`,
  ...Object.entries(keys).map(([k, v]) => `${k}=${v}`),
  "",
].join("\n");
writeFileSync(new URL("../.env.testnet", import.meta.url), env, { mode: 0o600 });
console.log("wrote web/.env.testnet (keys not shown)");
